#!/usr/bin/env node
/**
 * Generates targets/live-activity/LucideGlyphs.swift: every Lucide icon (lucide-react-native, the
 * same set the bots home draws) as SVG path data, so the Live Activity widget can draw a bot's
 * Lucide tile from the icon name alone when the app has not stored the bot's icon in the keychain.
 *
 * One line per name: `Name\td1|d2|...`. Circles, ellipses, rects, lines and polylines are turned
 * into path data here, so the widget only parses paths (LucideTile.swift). Aliases (e.g. Edit) map
 * to their icon's data. Run from packages/app: `node scripts/gen-lucide-glyphs.mjs`.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = join(app, "node_modules/lucide-react-native");
const iconsDir = join(pkg, "dist/esm/icons");
const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;

const n = (v) => {
  const x = Number(v);
  if (!Number.isFinite(x)) throw new Error(`bad number ${v}`);
  return Math.round(x * 1000) / 1000;
};

function toPath(tag, a) {
  switch (tag) {
    case "path":
      return String(a.d);
    case "circle": {
      const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)];
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;
    }
    case "ellipse": {
      const [cx, cy, rx, ry] = [n(a.cx), n(a.cy), n(a.rx), n(a.ry)];
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`;
    }
    case "rect": {
      const [x, y, w, h] = [n(a.x ?? 0), n(a.y ?? 0), n(a.width), n(a.height)];
      let rx = a.rx ?? a.ry ?? 0;
      let ry = a.ry ?? a.rx ?? 0;
      rx = Math.min(n(rx), w / 2);
      ry = Math.min(n(ry), h / 2);
      if (!rx || !ry) return `M${x} ${y}h${w}v${h}h${-w}z`;
      return (
        `M${x + rx} ${y}h${n(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${n(h - 2 * ry)}` +
        `a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${n(-(w - 2 * rx))}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}` +
        `v${n(-(h - 2 * ry))}a${rx} ${ry} 0 0 1 ${rx} ${-ry}z`
      );
    }
    case "line":
      return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case "polyline":
    case "polygon": {
      const pts = String(a.points)
        .trim()
        .split(/[\s,]+/)
        .map(n);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i + 1 < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === "polygon" ? `${d}z` : d;
    }
    default:
      throw new Error(`unknown tag ${tag}`);
  }
}

// kebab file name -> data, via each file's __iconData literal (JSON-like object syntax).
const byFile = new Map();
for (const file of readdirSync(iconsDir)) {
  if (!file.endsWith(".mjs") || file === "index.mjs") continue;
  const src = readFileSync(join(iconsDir, file), "utf8");
  const m = src.match(/const __iconData = (\{[\s\S]*?\n\});\n/);
  if (!m) throw new Error(`no __iconData in ${file}`);
  // eslint-disable-next-line no-new-func
  const { node } = new Function(`return ${m[1]}`)();
  const paths = node.map(([tag, attrs]) => toPath(tag, attrs));
  for (const p of paths) if (/[|\t\n"\\]/.test(p)) throw new Error(`bad char in ${file}`);
  byFile.set(file.replace(/\.mjs$/, ""), paths.join("|"));
}

// Exported names (canonical + aliases) -> file, from the package index.
const index = readFileSync(join(pkg, "dist/esm/lucide-react-native.mjs"), "utf8");
const lines = [];
const seen = new Set();
for (const m of index.matchAll(/export \{([^}]*)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g)) {
  const data = byFile.get(m[2]);
  if (!data) continue;
  for (const part of m[1].split(",")) {
    const name = part.trim().match(/^default as ([A-Za-z0-9]+)$/)?.[1];
    if (!name || seen.has(name) || name.endsWith("Icon") || name.startsWith("Lucide")) continue;
    seen.add(name);
    lines.push(`${name}\t${data}`);
  }
}
if (lines.length < 1000) throw new Error(`only ${lines.length} icons`);
lines.sort();

const out = `// Generated by scripts/gen-lucide-glyphs.mjs from lucide-react-native ${version}. Do not edit.
// ${lines.length} names (icons and aliases). Line format: Name<TAB>pathData|pathData|...
enum LucideGlyphs {
  static let version = "${version}"
  static let table = #"""

${lines.join("\n")}

"""#
}
`;
writeFileSync(join(app, "targets/live-activity/LucideGlyphs.swift"), out);
console.log(`LucideGlyphs.swift: ${lines.length} names, ${out.length} bytes`);
