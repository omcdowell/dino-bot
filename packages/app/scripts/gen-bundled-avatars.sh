#!/bin/zsh
# Generates targets/live-activity/BundledAvatars.swift: the bots' avatars built into the Live
# Activity widget, so a known bot shows its avatar even when the widget cannot read the icon the
# app stored in the keychain. Input: a folder of <bot-id>.png (the bots' .bot.json avatars). Each
# is scaled down to 96 px (the size the app stores) and embedded as base64. macOS only (sips).
# Usage: scripts/gen-bundled-avatars.sh <folder>
set -e
SRC=${1:?usage: gen-bundled-avatars.sh <folder of bot-id.png>}
OUT=${0:A:h}/../targets/live-activity/BundledAvatars.swift
WORK=$(mktemp -d)
trap 'rm -rf $WORK' EXIT
{
  echo "// Generated by scripts/gen-bundled-avatars.sh. Do not edit."
  echo "import Foundation"
  echo "import UIKit"
  echo ""
  echo "/// The bots' avatars built into the widget (96 px PNG, base64), by bot id. Used when the"
  echo "/// keychain has no icon for the bot (see WidgetBotImage); new bots need the keychain copy."
  echo "enum BundledAvatars {"
  echo "  static func image(_ id: String) -> UIImage? {"
  echo "    guard let base64 = table[id], let data = Data(base64Encoded: base64) else { return nil }"
  echo "    return UIImage(data: data)"
  echo "  }"
  echo ""
  echo "  static let table: [String: String] = ["
  for f in $SRC/*.png(N); do
    id=${f:t:r}
    [[ $id =~ '^[A-Za-z0-9._-]{1,64}$' ]] || continue
    sips -s format png -Z 96 $f --out $WORK/$id.png >/dev/null
    echo "    \"$id\": \"$(base64 -i $WORK/$id.png | tr -d '\n')\","
  done
  echo "  ]"
  echo "}"
} > $OUT
echo "wrote $OUT ($(wc -c < $OUT) bytes)"
